#!/usr/bin/env python3
"""Copy the home page's menu bar styles into assets/gpt/site-header.css.

The home header is shaped by a few hundred rules spread through site.css and
final-overrides.css. Gallery and Translate need exactly the same bar, but loading those
whole stylesheets there would restyle their content (they share class names such as
.eyebrow, .choice and .toast). This keeps every rule that targets the header, in load
order and inside its @media block, trims each selector list to its header selectors,
and adds the home page's custom properties (scoped to .site-header, so a page's own
tokens of the same name are untouched) and the @keyframes those rules use.

Run again whenever the home header's styles change:
  python3 scripts/build-site-header-css.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ["assets/gpt/site.css", "assets/gpt/final-overrides.css"]  # the order index.html loads them
OUT = ROOT / "assets/gpt/site-header.css"
HEADER = re.compile(
    r"(site-header|\.brand\b|brand-logo|nav-links|nav-link|nav-cta|invitation-replay|nav-translate|nav-pill"
    r"|nav-language|menu-toggle|mobile-current|mobile-nav-controls|menu-open)"
)


def strip_comments(css):
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def parse(css):
    """Split CSS into (prelude, body) blocks; @-rule bodies containing rules are parsed recursively."""
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        body = css[j + 1 : k - 1]
        # statements such as @import end with ";" and can sit before a block
        prelude = prelude.split(";")[-1].strip()
        if prelude.startswith(("@media", "@supports")):
            out.append((prelude, parse(body)))
        else:
            out.append((prelude, body.strip()))
        i = k
    return out


def split_selectors(prelude):
    parts, depth, cur = [], 0, ""
    for ch in prelude:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def pick(blocks, keep_root=True):
    rules, root_vars, used_anims = [], [], set()
    for prelude, body in blocks:
        if isinstance(body, list):
            inner, inner_vars, inner_anims = pick(body)
            used_anims |= inner_anims
            if inner_vars:
                rules.append(f"{prelude}{{.site-header{{{';'.join(inner_vars)}}}}}")
            if inner:
                rules.append(f"{prelude}{{\n" + "\n".join("  " + r for r in inner) + "\n}")
            continue
        if prelude.startswith("@"):
            continue  # keyframes and font-faces are handled separately
        sels = split_selectors(prelude)
        if keep_root and any(s.strip() == ":root" for s in sels):
            decls = [d.strip() for d in body.split(";") if d.strip().startswith("--")]
            if decls:
                root_vars.extend(decls)
        header = [s for s in sels if HEADER.search(s)]
        if header:
            rules.append(f"{','.join(header)}{{{body}}}")
            for m in re.finditer(r"animation(?:-name)?\s*:\s*([^;}]+)", body):
                used_anims.update(re.findall(r"[A-Za-z_-][\w-]*", m.group(1)))
    return rules, root_vars, used_anims


def keyframes(css):
    found = {}
    for m in re.finditer(r"@(?:-webkit-)?keyframes\s+([\w-]+)\s*\{", css):
        depth, k = 1, m.end()
        while k < len(css) and depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        found[m.group(1)] = css[m.start() : k]  # a later definition wins, as in the browser
    return found


def main():
    lines = [
        "/* Generated by scripts/build-site-header-css.py from site.css and final-overrides.css.",
        "   The home page's menu bar, for Gallery and Translate. Do not edit by hand; re-run the script. */",
    ]
    all_vars, all_anims, frames = [], set(), {}
    total = 0
    for src in SOURCES:
        css = strip_comments((ROOT / src).read_text())
        frames.update(keyframes(css))
        rules, root_vars, anims = pick(parse(css))
        all_vars.extend(root_vars)
        all_anims |= anims
        lines.append(f"\n/* ── from {src} ── */")
        if root_vars:
            # scoped to the header, so the page's own tokens of the same name are untouched
            lines.append(".site-header{" + ";".join(root_vars) + "}")
        lines.extend(rules)
        total += len(rules)
    wanted = [frames[a] for a in sorted(all_anims) if a in frames]
    if wanted:
        lines.append("\n/* ── animations the header uses ── */")
        lines.extend(wanted)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {total} rule groups, {len(all_vars)} custom properties, {len(wanted)} keyframes, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
